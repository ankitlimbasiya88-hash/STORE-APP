const START_B = 104;
const STOP = 106;

/** Encode a UTF-8 string using Code128 set B (printable ASCII 32-127). */
export function encodeCode128B(data: string): number[] {
  // Filter to printable ASCII; non-ASCII chars are dropped silently.
  const codes: number[] = [];
  codes.push(START_B);
  let checksum = START_B;
  let pos = 1;
  for (let i = 0; i < data.length; i++) {
    const ch = data.charCodeAt(i);
    if (ch < 32 || ch > 127) continue; // skip non-printable
    const val = ch - 32;
    codes.push(val);
    checksum += val * pos;
    pos++;
  }
  codes.push(checksum % 103);
  codes.push(STOP);
  // Flatten module widths
  const widths: number[] = [];
  for (const c of codes) {
    const pat = PATTERNS[c];
    for (const w of pat) widths.push(w);
  }
  return widths;
}
